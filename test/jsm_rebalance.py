def main():
    c = con()
    tp = topix(c)
    tdays = tp.index
    px = c.execute("SELECT Date, Code, AdjO, AdjC, Va FROM bars WHERE AdjC>0 AND AdjO>0").df()
    px['Date'] = pd.to_datetime(px.Date)
    px = px[px.Date.isin(tdays)]
    W = {k: px.pivot(index='Date', columns='Code', values=k).reindex(tdays) for k in ['AdjO', 'AdjC', 'Va']}
    va = W['Va'].rolling(20, min_periods=10).median()
    j400 = {ann: (set(a.split()), set(d.split())) for ann, _, a, d in J400}

    def pos(d, side):
        return int(np.searchsorted(tdays, pd.Timestamp(d), side=side))

    rows = []
    for ann, eff, adds, dels in EVENTS:
        a0 = pos(ann, 'right') - 1   # 発表日
        a = a0 + 1                   # 発表の翌営業日
        b = pos(eff, 'left') - 1     # 組み入れの日
        z, p = b + W2_DAYS, a0 - P0_DAYS
        up, dn = j400.get(ann, (set(), set()))
        for side, codes in ((1, adds.split()), (-1, dels.split())):
            for k in codes:
                code = k + '0'
                grp = ('del' if side < 0 else 'add') + ('_to400' if k in up else '_from400' if k in dn else '')
                if code not in W['AdjC'].columns:
                    rows.append(dict(ann=ann, code=k, grp=grp, note='データ無し'))
                    continue
                O, C = W['AdjO'][code].values, W['AdjC'][code].values
                cost = (float(liq_cost_bp(np.nan_to_num(va[code].values[a0]))) + SLIP_BP) / 1e4
                r = dict(ann=ann, code=k, grp=grp, side=side)
                if np.isfinite(O[a]) and np.isfinite(C[b]):
                    ex = (C[b] / O[a] - 1) - (tp.close.iloc[b] / tp.open.iloc[a] - 1)
                    r['d1_ex'] = ex
                    # 除外は買い、採用は売り（貸株料つき）
                    r['d1'] = -side * ex - cost - (BORROW * (b - a + 1) / 245 if side > 0 else 0)
                if p >= 0 and np.isfinite(C[p]) and np.isfinite(C[a0]):
                    r['p0_ex'] = (C[a0] / C[p] - 1) - (tp.close.iloc[a0] / tp.close.iloc[p] - 1)
                if z < len(tdays) and np.isfinite(C[b]) and np.isfinite(C[z]):
                    r['w2_ex'] = (C[z] / C[b] - 1) - (tp.close.iloc[z] / tp.close.iloc[b] - 1)
                    r['w2'] = -side * r['w2_ex'] - cost - (BORROW * W2_DAYS / 245 if side > 0 else 0)
                rows.append(r)
    df = pd.DataFrame(rows)
    df.to_csv(f'{OUT}/jsm_rebalance.csv', index=False)
    if 'note' in df:
        print('データ無し:', df[df.note.notna()][['ann', 'code', 'grp']].to_dict('records'), flush=True)
        df = df[df.note.isna()]
    pd.set_option('display.width', 200)
    print('件数:', df.groupby('grp').size().to_dict())

    def table(d, w, name, judge=False):
        d = d.dropna(subset=[w])
        per = d.groupby('ann').agg(n=(w, 'size'), net_bp=(w, 'mean'), ex_bp=(f'{w}_ex', 'mean'))
        per[['net_bp', 'ex_bp']] *= 1e4
        x = per.net_bp
        isx, oos = x[pd.to_datetime(x.index) <= IS_END], x[pd.to_datetime(x.index) > IS_END]
        t = x.mean() / x.std(ddof=1) * np.sqrt(len(x))
        med = d[w].median() * 1e4
        print(f'\n=== {name}')
        print(per.round(1).to_string())
        print(f'回の平均 {x.mean():+.1f} bp  t {t:+.2f}  正 {int((x > 0).sum())}/{len(x)}  '
              f'IS {isx.mean():+.1f} ({len(isx)})  OOS {oos.mean():+.1f} ({len(oos)})  銘柄の中央値 {med:+.1f}  '
              f'銘柄の勝率 {(d[w] > 0).mean():.0%}')
        if judge:
            c1, c2, c3, c4 = isx.mean() > 0 and oos.mean() > 0, t >= 2.0, int((x > 0).sum()) >= 7, med > 0
            print(f'判定 D1: 1 {c1}  2 {c2}  3 {c3}  4 {c4}  → {"採用候補" if c1 and c2 and c3 and c4 else "不採用"}')

    table(df[df.grp == 'del'], 'd1', 'D1 除外（400 と重ならない）を発表の翌寄りで買う→組み入れの日の引け', judge=True)
    table(df[df.grp == 'add'], 'd1', '（報告）採用（400 と重ならない）を売る')
    table(df[df.grp == 'del_to400'], 'd1', '（報告）除外のうち 400 の採用へ上がる銘柄を買う')
    table(df[df.grp == 'del_from400'], 'd1', '（報告）除外のうち 400 の除外と重なる銘柄を買う')
    table(df[df.grp == 'del'], 'w2', '（報告）W2 除外を組み入れの日の引けから 10 営業日持つ')
    g = df.dropna(subset=['p0_ex']).groupby(['ann', 'grp']).p0_ex.mean().unstack() * 1e4
    print('\n=== （報告）P0 発表前 20 営業日の超過（bp）')
    print(g.round(1).to_string())
    print('全回の平均:', g.mean().round(1).to_dict())


if __name__ == '__main__':
    main()
