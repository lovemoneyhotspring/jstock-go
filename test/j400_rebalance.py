def main():
    c = con()
    tp = topix(c)
    tdays = tp.index
    px = c.execute("SELECT Date, Code, AdjO, AdjC, Va, MktCap FROM bars WHERE AdjC>0 AND AdjO>0").df()
    px['Date'] = pd.to_datetime(px.Date)
    px = px[px.Date.isin(tdays)]
    W = {k: px.pivot(index='Date', columns='Code', values=k).reindex(tdays) for k in ['AdjO', 'AdjC', 'Va', 'MktCap']}
    va = W['Va'].rolling(20, min_periods=10).median()
    mg = c.execute("SELECT Date, Code, Mrgn FROM master").df()
    mg['Date'] = pd.to_datetime(mg.Date)
    mg = mg.sort_values('Date')

    def pos_after(d):
        return int(np.searchsorted(tdays, pd.Timestamp(d), side='right'))

    def pos_at(d):
        return int(np.searchsorted(tdays, pd.Timestamp(d), side='right')) - 1

    def pos_before(d):
        return int(np.searchsorted(tdays, pd.Timestamp(d), side='left')) - 1

    def shortable(code, d):
        s = mg[(mg.Code == code) & (mg.Date <= pd.Timestamp(d))]
        return bool(len(s)) and str(s.Mrgn.iloc[-1]) == '2'

    rows = []
    for ann, eff, adds, dels in EVENTS:
        a0 = pos_at(ann)             # 発表日
        a = pos_after(ann)           # 発表の翌営業日
        b = pos_before(eff)          # 実施日の前営業日（組み入れの日）
        z = b + W2_DAYS
        p = a0 - P0_DAYS
        for side, codes in ((1, adds.split()), (-1, dels.split())):
            for k in codes:
                code = k + '0'
                if code not in W['AdjC'].columns:
                    rows.append(dict(ann=ann, code=k, side=side, note='データ無し'))
                    continue
                O, C = W['AdjO'][code].values, W['AdjC'][code].values
                cost = (float(liq_cost_bp(np.nan_to_num(va[code].values[a0]))) + SLIP_BP) / 1e4
                r = dict(ann=ann, code=k, side=side, shortable=shortable(code, ann),
                         mcap=W['MktCap'][code].values[a0])
                if np.isfinite(O[a]) and np.isfinite(C[b]):
                    ex = (C[b] / O[a] - 1) - (tp.close.iloc[b] / tp.open.iloc[a] - 1)
                    hold = b - a + 1
                    r['r1_ex'] = ex
                    r['r1'] = -side * ex - cost - (BORROW * hold / 245 if side > 0 else 0)
                    r['f1'] = side * ex - cost - (BORROW * hold / 245 if side < 0 else 0)
                if np.isfinite(C[p]) and np.isfinite(C[a0]):
                    r['p0_ex'] = (C[a0] / C[p] - 1) - (tp.close.iloc[a0] / tp.close.iloc[p] - 1)
                if z < len(tdays) and np.isfinite(C[b]) and np.isfinite(C[z]):
                    ex2 = (C[z] / C[b] - 1) - (tp.close.iloc[z] / tp.close.iloc[b] - 1)
                    r['w2_ex'] = ex2
                    r['w2'] = -side * ex2 - cost - (BORROW * W2_DAYS / 245 if side > 0 else 0)
                rows.append(r)
    df = pd.DataFrame(rows)
    df.to_csv(f'{OUT}/j400_rebalance.csv', index=False)
    if 'note' in df:
        print('データ無し:', df[df.note.notna()][['ann', 'code', 'side']].to_dict('records'), flush=True)
        df = df[df.note.isna()]

    pd.set_option('display.width', 200)
    for w, name in (('r1', 'R1 発表の翌寄り→組み入れの日の引け（採用を売り・除外を買う）'),
                    ('f1', 'F1 R1 の逆向き（報告だけ）'),
                    ('w2', 'W2 組み入れの日の引け→10 営業日後（採用を売り・除外を買う、報告だけ）')):
        ex = 'r1_ex' if w in ('r1', 'f1') else f'{w}_ex'
        d = df.dropna(subset=[w])
        g = d.groupby('ann')
        per = pd.DataFrame({'n': g.size(), 'net_bp': g[w].mean() * 1e4,
                            'add_ex_bp': g.apply(lambda x: x.loc[x.side > 0, ex].mean() * 1e4),
                            'del_ex_bp': g.apply(lambda x: x.loc[x.side < 0, ex].mean() * 1e4)})
        x = per.net_bp
        isx, oos = x[pd.to_datetime(x.index) <= IS_END], x[pd.to_datetime(x.index) > IS_END]
        t = x.mean() / x.std(ddof=1) * np.sqrt(len(x))
        legs = d.groupby('side')[w].mean() * 1e4
        print(f'\n=== {name}')
        print(per.round(1).to_string())
        print(f'回の平均 {x.mean():+.1f} bp  t {t:+.2f}  正 {int((x > 0).sum())}/{len(x)}  '
              f'IS {isx.mean():+.1f} ({len(isx)})  OOS {oos.mean():+.1f} ({len(oos)})')
        print(f'脚ごとの純損益（全銘柄の平均、bp）: 採用 {legs.get(1, np.nan):+.1f}  除外 {legs.get(-1, np.nan):+.1f}')
        if w == 'r1':
            c1, c2, c3 = isx.mean() > 0 and oos.mean() > 0, t >= 2.0, int((x > 0).sum()) >= 8
            c4 = legs.get(1, -1) > 0 and legs.get(-1, -1) > 0
            print(f'判定 R1: 1 {c1}  2 {c2}  3 {c3}  4 {c4}  → {"採用候補" if c1 and c2 and c3 and c4 else "不採用"}')

    g = df.dropna(subset=['p0_ex']).groupby(['ann', 'side']).p0_ex.mean().unstack() * 1e4
    print(f'\n=== P0 発表の 20 営業日前の引け→発表日の引けの超過（bp、報告だけ）')
    print(g.rename(columns={1: '採用', -1: '除外'}).round(1).to_string())
    print('全回の平均:', (g.mean()).round(1).to_dict())
    ns = df[(df.side > 0) & ~df.shortable.astype(bool)].shape[0]
    print(f'\nR1 で売る採用銘柄のうち貸借でないもの: {ns}/{int((df.side > 0).sum())}')
    print('時価総額の中央値（億円）:', (df.groupby('side').mcap.median() / 1e8).round(0).to_dict())


if __name__ == '__main__':
    main()
